/* The read-only panel beside the editor: everything this profile will wear.
 *
 * Its own file for two reasons. `Editor.jsx` is past the 800-line ceiling and
 * may not grow, and this panel now has a rule of its own worth stating: it must
 * not present a field as fact when the chosen engine is going to ignore it.
 *
 * Camoufox is the case that forced it. `drivers.py:_camoufox_kwargs` passes the
 * browser four things - os, locale, the proxy, and geoip when the profile asked
 * to follow its exit IP - and generates the rest itself, coherently, as a
 * Firefox. The panel used to print `Chrome 128`, a user agent, a resolution and
 * a WebGL vendor for such a profile anyway, all of them stated as settled. They
 * are not settled; they are not even sent. Camoufox is the recommended engine,
 * so this was the common reading, not an edge case.
 *
 * What it does NOT do is hide the values. They stay visible and editable,
 * because switching the engine to a Chromium one makes every one of them live
 * again - they are simply marked as what they are while another engine is
 * selected.
 */

import { ShieldAlert } from "lucide-react";
import { ENGINE_META, generatesOwnIdentity } from "../deviceData";
import { T } from "../theme";

const lines = v => Array.isArray(v) ? v.length
  : String(v || "").split(/\r?\n/).filter(l => l.trim()).length;

//: The rows an engine-built identity overrides - marked, never silently shown.
const ENGINE_BUILT_ROWS = new Set([
  "Browser", "User-Agent", "Resolution", "WebRTC", "Canvas", "Client Rects",
  "WebGL Image", "WebGL Vendor", "Audio Context", "Fonts", "Media devices", "CPU / RAM",
]);

function ProfileSummary({ p, issues, score }) {
  const engineBuilt = generatesOwnIdentity(p.engine);
  const engineLabel = ENGINE_META[p.engine]?.label || p.engine;
  const rows = [
    ["Profile name", p.name || "Untitled profile"],
    ["Folder", p.folder || "None"],
    ["Engine", ENGINE_META[p.engine]?.label || p.engine || "default"],
    ["Proxy", p.proxy ? `${p.proxy.type} ${p.proxy.host}:${p.proxy.port}` : "Direct"],
    ["OS", p.os],
    ["Browser", engineBuilt ? "Firefox" : `Chrome ${p.browserVersion || ""}`.trim()],
    ["User-Agent", p.userAgent],
    ["Resolution", p.screen],
    ["Languages", p.locale],
    ["Timezone", p.timezone],
    ["Geolocation", p.geo],
    ["WebRTC", p.webrtc],
    ["Canvas", p.canvas],
    ["Client Rects", p.clientRects || "noise"],
    ["WebGL Image", p.webglImage || "noise"],
    ["WebGL Vendor", p.webglVendor],
    ["Audio Context", p.audio],
    ["Fonts", p.fonts === "Real" || p.fonts === "real" ? "real"
      : `masked (${String(p.fontList || "").split(/\r?\n/).filter(Boolean).length || "default"})`],
    ["Media devices", p.mediaDevices === "real" ? "real"
      : `${p.mediaVideo ?? 1}/${p.mediaAudio ?? 1}/${p.mediaSpeakers ?? 1}`],
    ["CPU / RAM", `${p.cores} threads · ${p.memory} GB`],
    ["Do Not Track", p.dnt ? "on" : "off"],
    ["Extensions", lines(p.extensions) || "none"],
    ["Startup URLs", lines(p.startupUrls) || "none"],
    ["Bookmarks", lines(p.bookmarks) || "none"],
    ["Launch args", lines(p.launchArgs) || "none"],
    ["DNS", p.dns || "system default"],
    ["Follows exit IP", (p.ipBased || []).join(", ") || "nothing"],
    ["Cleared each launch", (p.clearOnStart || []).join(", ") || "nothing"],
    ["Switched off", (p.switchedOff || []).join(", ") || "nothing"],
  ];
  return (
    <aside className="ps-summary">
      <div className="ps-summary-h">
        <span>Profile summary</span>
        <span style={{ color: issues.length ? T.amber : T.mint, fontWeight: 700 }}>{score}%</span>
      </div>
      {engineBuilt && (
        <div className="ps-summary-note">
          {engineLabel} builds its own fingerprint. It is given this profile&apos;s OS,
          language and proxy; the marked rows below are generated by the browser and
          take effect only on a Chromium engine.
        </div>
      )}
      <dl className="ps-summary-list">
        {rows.map(([k, v]) => {
          const built = engineBuilt && ENGINE_BUILT_ROWS.has(k);
          return (
            <div key={k} className="ps-summary-row">
              <dt>{k}</dt>
              <dd title={built ? `${engineLabel} generates this — the stored value is "${v}"` : String(v ?? "")}
                  style={built ? { color: T.dim } : undefined}>
                {built ? `${v === "" || v == null ? "—" : String(v)} · generated` : (v === "" || v == null ? "—" : String(v))}
              </dd>
            </div>
          );
        })}
      </dl>
      {issues.length > 0 && (
        <div className="ps-summary-iss">
          <ShieldAlert size={13} /> {issues.length} contradiction{issues.length === 1 ? "" : "s"}
          {issues.map((i, k) => <div key={k}>· {i}</div>)}
        </div>
      )}
    </aside>
  );
}

export { ProfileSummary };
